'use strict';
const test = require('node:test'), assert = require('node:assert/strict'), fs = require('node:fs'), path = require('node:path');
const { createSalesReportLibraryPreview } = require('../test-support/sales-report-library-preview.cjs');
test('report explorer supports context actions, counts, real drag/drop, sorting and persisted accessible column layouts', {
  skip: process.env.GP_SALES_ANALYTICS_BROWSER_TEST !== '1', timeout: 60000
}, async t => {
  const preview = createSalesReportLibraryPreview(), server = preview.app.listen(0, '127.0.0.1'); await new Promise(r => server.once('listening', r));
  t.after(() => new Promise(r => server.close(r)));
  const { chromium } = require(process.env.GP_BROWSER_TEST_MODULE || 'playwright');
  const browser = await chromium.launch({ headless: true, ...(process.env.GP_BROWSER_EXECUTABLE ? { executablePath: process.env.GP_BROWSER_EXECUTABLE } : {}) });
  t.after(() => browser.close());
  const page = await browser.newPage({ viewport: { width: 1500, height: 1050 } }), errors = [];
  page.setDefaultTimeout(8000); page.on('pageerror', e => errors.push(e.message));
  const url = 'http://127.0.0.1:' + server.address().port;
  const ready = () => page.waitForFunction(() => !document.getElementById('salesAnalyticsReportsPanel').hasAttribute('aria-busy'));
  const screenshot = async name => { if (process.env.GP_SALES_ANALYTICS_SCREENSHOTS) { fs.mkdirSync(process.env.GP_SALES_ANALYTICS_SCREENSHOTS, { recursive: true }); await page.screenshot({ path: path.join(process.env.GP_SALES_ANALYTICS_SCREENSHOTS, name), fullPage: true }); } };
  await page.goto(url);
  await page.waitForFunction(() => document.querySelectorAll('.sales-library-icon').length === 5);
  assert.equal(await page.locator('#salesLibraryFolderActions').count(), 0);
  assert.ok((await page.locator('.sales-library-header').boundingBox()).height < 80);
  assert.ok((await page.locator('#salesReportJobFilter').boundingBox()).height <= 32);
  await page.getByRole('button',{name:'Filiale 18 einklappen',exact:true}).click();
  assert.equal(await page.locator('#salesLibraryFolders [data-drop-folder="year2026"]').count(),0);
  await page.getByRole('button',{name:'Filiale 18 ausklappen',exact:true}).click();
  assert.equal(await page.locator('#salesLibraryFolders [data-drop-folder="year2026"]').count(),1);
  const reportTile=page.locator('.sales-library-icon[data-library-key="report:october"]');
  await reportTile.click({button:'right'});
  assert.equal(await page.getByRole('menuitem',{name:'PDF herunterladen',exact:true}).count(),1);
  await page.getByRole('menuitem',{name:'Als Vorlage für neuen Bericht verwenden',exact:true}).click();
  assert.equal(await page.locator('#previewReuse input').inputValue(),'Oktober 2026 · Filiale 18');await page.keyboard.press('Escape');
  await screenshot('08-explorer-icons.png');
  const parent = page.locator('#salesLibraryFolders [data-drop-folder="fil18"]');
  await parent.click({ button: 'right' });
  assert.equal(await page.getByRole('menuitem', { name: 'Ordner umbenennen' }).count(), 1);
  await screenshot('09-explorer-context-menu.png');
  await page.getByRole('menuitem', { name: 'Eigenschaften' }).click();
  assert.match(await page.locator('#salesLibraryPropertiesDetails').textContent(), /Dateien direkt im Ordner4Berichte inkl\. Unterordner3Vorlagen inkl\. Unterordner2Unterordner insgesamt1/);
  await screenshot('10-explorer-folder-properties.png'); await page.keyboard.press('Escape');
  const folder = page.locator('.sales-library-icon[data-library-key="folder:year2026"]');
  await page.locator('.sales-library-icon[data-library-key="template:monthly"]').dragTo(folder);
  await page.waitForFunction(() => document.querySelectorAll('.sales-library-icon').length === 4); await ready();
  assert.equal(preview.snapshot().library.items.find(i => i.id === 'monthly').folderId, 'year2026');
  const revision = preview.snapshot().library.revision;
  await parent.dragTo(folder); assert.equal(preview.snapshot().library.revision, revision);
  assert.match(await page.locator('#salesLibraryFeedback').textContent(), /nicht in sich selbst/);
  await page.locator('#salesLibraryView').selectOption('details'); await ready();
  assert.equal(await page.locator('.sales-library-table tbody tr').count(), 4);
  await page.locator('tr[data-library-key="report:october"]').click({button:'right'});
  assert.equal(await page.getByRole('menuitem',{name:'Als Vorlage für neuen Bericht verwenden',exact:true}).count(),1);
  const download=page.waitForEvent('download');await page.getByRole('menuitem',{name:'PDF herunterladen',exact:true}).click();
  assert.equal((await download).suggestedFilename(),'Beispielbericht.pdf');
  assert.equal(await page.locator('#salesLibraryFeedback').evaluate(e=>e.getBoundingClientRect().height),1);

  assert.match(await page.locator('tr[data-library-key="template:margin"]').textContent(), /Nicht erfasst/);
  await page.getByRole('button', { name: /^Name ↑$/ }).click(); await ready();
  assert.equal(preview.snapshot().library.preferences.direction, 'desc');
  await page.locator('#salesReportJobList summary').click();
  await page.getByRole('checkbox', { name: 'Geändert am anzeigen' }).check(); await ready();
  await page.getByRole('checkbox', { name: 'Status anzeigen' }).uncheck(); await ready();
  await page.getByRole('button', { name: 'Geändert am nach links', exact: true }).click(); await ready();
  const handle = page.getByRole('slider', { name: 'Name – Spaltenbreite', exact: true });
  await handle.focus(); await handle.press('ArrowRight'); await ready();
  assert.ok(preview.snapshot().library.preferences.widths.name > 280);
  const rect = await handle.boundingBox(), before = preview.snapshot().library.preferences.widths.name;
  await page.mouse.move(rect.x + rect.width / 2, rect.y + 15); await page.mouse.down(); await page.mouse.move(rect.x + rect.width / 2 + 35, rect.y + 15); await page.mouse.up(); await ready();
  assert.ok(preview.snapshot().library.preferences.widths.name > before);
  await screenshot('11-explorer-details-and-columns.png');
  const saved = preview.snapshot().library.preferences; await page.reload();
  await page.waitForFunction(() => document.querySelector('.sales-library-table'));
  assert.equal(await page.locator('#salesLibraryView').inputValue(), 'details');
  assert.deepEqual(await page.locator('.sales-library-table th[data-column]').evaluateAll(cells => cells.map(c => c.dataset.column)), saved.columns);
  assert.equal(Number(await page.getByRole('slider', { name: 'Name – Spaltenbreite', exact: true }).getAttribute('aria-valuenow')), saved.widths.name);
  const row = page.locator('tr[data-library-key="report:october"]'); await row.focus(); await row.press('Shift+F10');
  await page.getByRole('menuitem', { name: 'Eigenschaften' }).click(); assert.match(await page.locator('#salesLibraryPropertiesDetails').textContent(), /Personalnr\. 101/); await page.keyboard.press('Escape');
  await row.dragTo(page.locator('#salesLibraryFolders [data-drop-folder="fil05"]'));
  await page.waitForFunction(() => !document.querySelector('tr[data-library-key="report:october"]')); await ready();
  assert.equal(preview.snapshot().library.items.find(i => i.id === 'october').folderId, 'fil05');
  assert.equal(preview.snapshot().reports.find(r => r.id === 'october').created, '2026-11-01T10:15:00.000Z');
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await screenshot('12-explorer-details-mobile.png');
  await page.locator('#salesReportJobList summary').click();
  for (const id of saved.columns.filter(id => id !== 'name')) { const label = require('../public/sales-report-library-options').COLUMNS.find(c => c.id === id).label; await page.getByRole('checkbox', { name: label + ' anzeigen', exact: true }).uncheck(); await ready(); }
  assert.equal(await page.getByRole('checkbox', { name: 'Name anzeigen', exact: true }).isDisabled(), true);
  assert.deepEqual(preview.snapshot().library.preferences.columns, ['name']);
  assert.deepEqual(errors, []);
});
