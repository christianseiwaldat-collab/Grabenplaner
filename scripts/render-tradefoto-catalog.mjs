// Offline documentation renderer and consistency checks; no application writes.
import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';

const [inputFile,mode='--check'] = process.argv.slice(2);
if (!inputFile || !['--check','--write'].includes(mode)) throw new Error('Usage: render-tradefoto-catalog.mjs catalog.json [--check|--write]');
const catalog=JSON.parse(fs.readFileSync(inputFile,'utf8'));
const handlingLabels = {
  existing_article_import:'Artikelimport vorhanden',
  existing_field_with_import_rules_missing:'GP-Feld vorhanden; Import fehlt',
  model_extension_proposed:'Zielerweiterung vorgeschlagen',
  semantic_review:'Fachregel offen',
  archive_proposed:'Getrennte Alt-/Prüfablage vorgesehen',
  secret_exception:'Geheimnis-Ausnahme',
  access_internal_metadata_only:'Nur Access-Metadaten',
};
const number=value=>new Intl.NumberFormat('de-AT').format(value);
const cell=value=>String(value ?? '–').replace(/\|/g,'\\|').replace(/[\r\n]+/g,' ');
const code=value=>'`'+cell(value).replace(/`/g,"'")+'`';
const row=values=>'| '+values.map(cell).join(' | ')+' |';
function validate(report) {
  assert.equal(report.format,'grabenplaner.tradefoto.full-inventory.v1');
  assert.equal(report.sourceHashesVerifiedAfterRead,true);
  const tables=report.sources.flatMap(source=>source.tables), fields=tables.flatMap(table=>table.columns);
  assert.equal(report.coverage.tables,tables.length);
  assert.equal(report.coverage.fields,fields.length);
  assert.equal(report.coverage.rowsScanned,tables.reduce((sum,table)=>sum+table.scannedRows,0));
  assert.equal(report.coverage.unclassifiedFields,0);
  for (const source of report.sources) {
    assert.match(source.sha256,/^[0-9a-f]{64}$/);
    assert.match(source.schemaSha256,/^[0-9a-f]{64}$/);
    assert.equal(new Set(source.tables.map(table=>table.name)).size,source.tables.length);
    for (const table of [...source.tables,...source.systemTables]) {
      assert.equal(new Set(table.columns.map(column=>column.name)).size,table.columns.length);
      if (table.scannedRows!==null) assert.equal(table.metadataRowDifference,table.declaredRows-table.scannedRows);
      for (const column of table.columns) {
        assert.ok(handlingLabels[column.destination.handling]);
        assert.ok(column.destination.target && column.destination.group && column.destination.dataClass);
        if (!column.destination.inspectValues) { assert.equal(column.profile,null); continue; }
        const profile=column.profile;
        assert.equal(profile.inspected,table.scannedRows);
        for (const field of ['null','emptyText','zero','positive','negative','true','false','invalid']) assert.ok(profile[field]>=0 && profile[field]<=profile.inspected);
        if (profile.type==='boolean') assert.equal(profile.null+profile.true+profile.false+profile.invalid,profile.inspected);
        if (['currency','numeric','double','float','byte','integer','long'].includes(profile.type)) assert.equal(profile.null+profile.zero+profile.positive+profile.negative+profile.invalid,profile.inspected);
        if (profile.type==='datetime' && !profile.dateRangeSuppressed) assert.equal(Object.values(profile.dateYears).reduce((a,b)=>a+b,0)+profile.null+profile.invalid,profile.inspected);
        if (profile.dateRangeSuppressed) { assert.equal(profile.dateMin,null); assert.equal(profile.dateMax,null); assert.deepEqual(profile.dateYears,{}); }
        if (/geburt|birth/i.test(column.name) && column.type==='datetime') assert.equal(profile.dateRangeSuppressed,true);
      }
    }
    for (const key of source.keys) assert.equal(key.rows,key.nullRows+key.distinctNonNull+key.duplicateRows);
  }
  for (const relation of report.relations) {
    const check=relation.check;
    assert.equal(check.childRows,check.nullChildRows+check.unassignedZeroRows+check.matchedRows+check.orphanRows);
    assert.ok(check.ambiguousRows<=check.matchedRows);
    assert.ok(check.unreferencedParentKeys<=check.parentDistinct);
  }
  const attribution=report.quality.sellerAttribution;
  assert.equal(attribution.rows,['matchingNonZero','bothZero','differentNonZero','lineZeroHeaderNonZero','lineNonZeroHeaderZero','missingHeader','missingSellerValue'].reduce((sum,key)=>sum+attribution[key],0));
}
validate(catalog);
// Regression guards for incomplete catalogs and leaked personal-date metadata.
for (const mutate of [
  report=>report.coverage.fields++,
  report=>report.sources[0].tables[0].columns[0].destination.handling='unknown',
  report=>{ const birthday=report.sources[0].tables.find(t=>t.name==='KUNDEN').columns.find(c=>c.name==='Geburtstag'); birthday.profile.dateMin='synthetic-invalid-output'; },
]) { const invalid=structuredClone(catalog); mutate(invalid); assert.throws(()=>validate(invalid)); }

const generated='<!-- Generated by scripts/render-tradefoto-catalog.mjs from catalog.json; no source row values. -->';
const fields=[generated,'# Vollständiger Feldkatalog','',
  'Block 1/6; nur Inventur und Zielvorschlag. Alle Fachtabellen einschließlich leerer Tabellen sind aufgeführt. Keine produktiven Importregeln freigegeben.',
  '', '[Einordnung und offene Entscheidungen](README.md) · [Tabellen, Schlüssel und Beziehungen](TABELLEN-UND-BEZIEHUNGEN.md)', '',
  '## Legende','',
  '„Belegt“ bedeutet weder NULL noch leerer Text; numerische 0 und false zählen dabei als vorhanden, nicht automatisch als fachlich zugeordnet. „Nullen“ zählt nur numerische 0. Größe/Nullable/Auto stammen aus der Leser-Metadatensicht; Auto ist kein Primärschlüsselnachweis. Datumsbereiche sind Reader-Repräsentationen lokaler Access-Zeiten; Z ist kein belegter UTC-Quellbezug. Personenbezogene Datumsbereiche werden nicht veröffentlicht.', '',
  'Ein Ziel mit `source_fields[...]` bezeichnet eine typisierte Herkunfts-/Prüfablage im vorgeschlagenen Fachbereich, noch kein beschlossenes GP-Datenbankfeld. Unbekannte Bedeutungen bleiben dort erhalten und werden nicht als Kennzahl oder aktive Einstellung verwendet.', '',
  row(['Status','Bedeutung']),row(['---','---']),...Object.entries(handlingLabels).map(([key,label])=>row([code(key),label])),''];
const overview=[generated,'# Tabellen, Schlüssel und Beziehungen','',
  '[Einordnung und offene Entscheidungen](README.md) · [Vollständiger Feldkatalog](FELDKATALOG.md)', '',
  `${number(catalog.coverage.tables)} Fachtabellen, ${number(catalog.coverage.fields)} Felder, ${number(catalog.coverage.rowsScanned)} gelesene Fachzeilen. Zeilenzahlen verschiedener Fach-/Aggregat-/Archivtabellen dürfen nicht als gemeinsame Umsatzgröße interpretiert werden.`, ''];
for (const source of catalog.sources) {
  overview.push('## '+source.fileName,'',row(['Tabelle','Zeilen laut Metadaten','Gelesen','Differenz','Felder','Zielbereich']),row(['---','---:','---:','---:','---:','---']));
  for (const table of source.tables) overview.push(row([code(table.name),number(table.declaredRows),number(table.scannedRows),number(table.metadataRowDifference),table.columns.length,code(table.group)]));
  overview.push('',`Verknüpfte Tabellen: ${source.linkedTables.map(code).join(', ') || 'keine'}. Nicht als eigenständige Tabelle dieser Datei ausgelesen.`, '',
    `Access-Systemtabellen: ${source.systemTables.length}; deren Werte wurden nicht analysiert, ausgenommen deklarierte Beziehungsmetadaten. Schema und Metadatenzeilenzahlen stehen im Feldkatalog.`, '',
    '### Geprüfte Schlüsselkandidaten','',
    'Vollständigkeit und Eindeutigkeit gelten für diesen Snapshot. Keine Liste deklarierter Primärschlüssel oder Indizes. Dubletten = zusätzliche Zeilen je nicht leerem Schlüssel; keine Lösch-/Zusammenführungsanweisung.', '',
    row(['Tabelle','Kandidat','Zeilen','NULL im Schlüssel','Verschieden','Zusätzliche Dubletten']),row(['---','---','---:','---:','---:','---:']));
  for (const key of source.keys) overview.push(row([code(key.table),key.columns.map(code).join(' + '),number(key.rows),number(key.nullRows),number(key.distinctNonNull),number(key.duplicateRows)]));
  overview.push('');
  fields.push('## '+source.fileName,'');
  for (const table of [...source.tables,...source.systemTables]) {
    fields.push('### '+code(table.name),'',
      `Bereich: ${code(table.group)}. Metadaten: ${number(table.declaredRows)} Zeilen; gelesen: ${table.scannedRows===null?'nicht gelesen (Systemschema)':number(table.scannedRows)}.`, '',
      row(['Quellfeld','Access-Typ / Größe','Nullable / Auto','Belegt','NULL / leer / Nullen','Profilhinweis','GP-Ziel / Status / Datenklasse']),row(['---','---','---','---:','---','---','---']));
    for (const column of table.columns) {
      const p=column.profile,d=column.destination, hints=[];
      if (p?.dateRangeSuppressed) hints.push('Personendatumsbereich unterdrückt');
      else if (p?.dateMin) hints.push(`${p.dateMin} bis ${p.dateMax}`);
      if (p?.negative) hints.push(`${number(p.negative)} negativ`);
      if (p?.type==='boolean') hints.push(`${number(p.true)} true / ${number(p.false)} false`);
      if (p?.maxTextLength) hints.push(`Text max. ${number(p.maxTextLength)} Zeichen`);
      if (p?.textControlCharacters) hints.push(`${number(p.textControlCharacters)} mit Steuerzeichen`);
      if (p?.invalid) hints.push(`${number(p.invalid)} typauffällig`);
      if (p && Object.values(p.references).some(Boolean)) hints.push('Datei-/Medienverweise (nicht geöffnet)');
      const nullable=column.nullable===undefined?'unbekannt':String(column.nullable);
      fields.push(row([code(column.name),`${column.type} / ${column.size ?? '–'}`,`${nullable} / ${column.autoLong?'autoLong':column.autoUUID?'autoUUID':'–'}`,
        p?number(p.inspected-p.null-p.emptyText):'nicht geprüft',p?`${number(p.null)} / ${number(p.emptyText)} / ${number(p.zero)}`:'–',hints.join('; ')||'–',
        `${code(d.target)} · ${handlingLabels[d.handling]} · ${code(d.dataClass)}. ${d.note}`]));
    }
    fields.push('');
  }
}
overview.push('## Beziehungen','',
  '„Access“ ist eine deklarierte Beziehung; „Kandidat“ eine zusätzlich geprüfte Verknüpfung. Verglichen wird exakter, getrimmter Text. Nicht erfüllte Verknüpfungen werden nicht repariert. NULL und unzugeordnete 0 werden gesondert ausgewiesen; mehrdeutige Treffer sind Teil der Trefferzahl. Rohflags und die Namen deklarierter Beziehungen sind in catalog.json enthalten, ohne daraus Constraint-Wirkung abzuleiten.', '',
  row(['Evidenz','Kindtabelle / Felder','Elterntabelle / Felder','Kindzeilen','NULL / unzugeordnete 0','Treffer / mehrdeutig','Ohne Ziel (Zeilen / Schlüssel)','Nicht referenzierte Elternschlüssel']),row(['---','---','---','---:','---','---','---','---:']));
for (const relation of catalog.relations) {
  const c=relation.check;
  overview.push(row([relation.evidence==='declared_in_access'?'Access':`Kandidat: ${relation.name}`,
    code(`${relation.childSource}.${relation.childTable}`)+' / '+relation.childColumns.map(code).join(' + '),
    code(`${relation.parentSource}.${relation.parentTable}`)+' / '+relation.parentColumns.map(code).join(' + '),
    number(c.childRows),`${number(c.nullChildRows)} / ${number(c.unassignedZeroRows)}`,`${number(c.matchedRows)} / ${number(c.ambiguousRows)}`,
    `${number(c.orphanRows)} / ${number(c.orphanKeys)}`,number(c.unreferencedParentKeys)]));
}
const outputs={'FELDKATALOG.md':fields.join('\n').trimEnd()+'\n','TABELLEN-UND-BEZIEHUNGEN.md':overview.join('\n').trimEnd()+'\n'};
for (const [file,contents] of Object.entries(outputs)) {
  const output=path.join(path.dirname(path.resolve(inputFile)),file);
  if (mode==='--check') assert.equal(fs.readFileSync(output,'utf8'),contents,`Generated report out of date: ${file}`);
  else {
    if (fs.existsSync(output) && !fs.readFileSync(output,'utf8').startsWith(generated)) throw new Error(`Refusing to replace unrelated file: ${file}`);
    fs.writeFileSync(output,contents);
  }
}
console.log(JSON.stringify({status:'PASS',mode,coverage:catalog.coverage,consistencyChecks:true,negativeRegressionChecks:3,outputs:Object.keys(outputs)}));
